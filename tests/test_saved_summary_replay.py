"""A captured complete response can be accepted with an exhausted native budget."""

import hashlib
import json
from pathlib import Path

import litellm
from error_transport import ErrorTransport

from ultrakb.agent.retained_summary import reuse_saved_summary
from ultrakb.application.execution import ExecutionContext
from ultrakb.config import save_config
from ultrakb.content_blocks import markdown_layout
from ultrakb.llm_execution import ModelRequest
from ultrakb.storage.checkpoint_store import CompileCheckpointStore
from ultrakb.storage.execution_store import ExecutionStore

FIXTURE = Path(__file__).parent / "fixtures" / "summary-third-response.json"
RESPONSE_SHA256 = "49c3d3e62345a94c5c5127fc346b3109ba0a7f098e601744893b995506737e72"


def test_captured_third_summary_replays_without_changing_accepted_results_or_budget(kb_dir):
    import pytest
    from compile_work_fixtures import checkpoint_record

    case = json.loads(FIXTURE.read_text("utf-8"))
    raw = case["response"]
    assert hashlib.sha256(raw.encode()).hexdigest() == RESPONSE_SHA256
    save_config(
        kb_dir / ".ultrakb/config.yaml",
        {
            "model": "openai/gpt-4o-mini",
            "model_policy": {"max_calls": 1, "retries": 0},
        },
    )
    with ErrorTransport(status=400) as service:
        (kb_dir / ".env").write_text(
            f"LLM_API_KEY=offline-replay-key\nOPENAI_API_BASE={service.url}\n"
        )
        context = ExecutionContext()
        with context.begin(kb_dir):
            with pytest.raises(litellm.BadRequestError):
                context.executor.complete(
                    "compile",
                    ModelRequest(
                        [{"role": "user", "content": "A prior local failed request."}],
                        operation="compile",
                        stage="prior-attempt",
                    ),
                )
            execution = context.storage_execution
            work = CompileCheckpointStore(kb_dir, context.storage_identity)
            checkpoint = work.for_work(
                execution.model_budget_id,
                object_id={"document": case["document"]},
                conditions={},
                execution_id=execution.execution_id,
            )
            retained = {}
            for accepted in case["accepted_summaries"]:
                checkpoint.save(accepted["key"], accepted["request_digest"], accepted["result"])
                retained[accepted["key"]] = checkpoint.load(
                    accepted["key"], accepted["request_digest"]
                )
            checkpoint.claim_repair("summary:3", case["request_digest"])
            checkpoint.record_invalid_response(
                "summary:3",
                case["request_digest"],
                raw,
                stage="document-summary:3",
                response_protocol="summary-json",
                expected_sections=tuple(case["expected_sections"]),
                code="page_literal_conflict",
                detail="Captured whitespace and excerpt-boundary rejection",
                attempt=1,
            )
            result = reuse_saved_summary(
                checkpoint,
                "summary:3",
                case["request_digest"],
                case["batch"],
                protocol="summary-json",
                section_ranges=case["batch"]["output_sections"],
            )
            assert result is not None
            assert [section["id"] for section in result["sections"]] == case["expected_sections"]
            assert result["description"] == case["accepted_description"]
            actual = []
            for section in result["sections"]:
                tokens, _ = markdown_layout(section["content"])
                actual.extend(
                    hashlib.sha256(token.content.rstrip("\n").encode()).hexdigest()
                    for token in tokens
                    if token.type == "fence"
                )
            assert len(actual) == 58
            # Ordinary fences retain generated bytes; explicit markers alone copy originals.
            manual = [
                token.content
                for section in json.loads(raw)["sections"]
                for token in markdown_layout(section["content"])[0]
                if token.type == "fence"
            ]
            delivered = [
                token.content
                for section in result["sections"]
                for token in markdown_layout(section["content"])[0]
                if token.type == "fence"
            ]
            assert len(manual) == 26
            assert all(body in delivered for body in manual)
            for accepted in case["accepted_summaries"]:
                assert (
                    checkpoint.load(accepted["key"], accepted["request_digest"])
                    == retained[accepted["key"]]
                )
            restored = work.for_work(
                execution.model_budget_id,
                object_id={"document": case["document"]},
                conditions={},
                execution_id=execution.execution_id,
            )
            assert restored.load("summary:3", case["request_digest"]) == result
            assert checkpoint_record(restored, "summary:3")["repair_used"] is True
            retained_raw = restored.retained_response(
                "summary:3",
                case["request_digest"],
                protocol="summary-json",
                sections=tuple(case["expected_sections"]),
                stage="document-summary:3",
            )
            assert retained_raw[0] == raw
            assert retained_raw[1]["response_sha256"] == RESPONSE_SHA256
            assert (
                ExecutionStore(kb_dir, context.storage_identity)
                .budget(execution.model_budget_id)
                .used
                == 1
            )
            assert len(service.requests) == 1
