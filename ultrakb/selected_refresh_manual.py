"""Keep proven human additions outside a source refresh's generated editing scope."""

from difflib import SequenceMatcher

from ultrakb.agent.page_updates import PageUpdate
from ultrakb.ingest_records import KnowledgeRevision
from ultrakb.state import HashRegistry


def manual_refresh_insertions(patch: PageUpdate, baseline: str) -> list[tuple[int, int]]:
    """Identify added lines, ignoring a preceding generated line's final newline."""
    generated = PageUpdate(baseline, source_ranges=patch.source_ranges).body.splitlines(
        keepends=True
    )
    current = patch.body.splitlines(keepends=True)
    offsets = [0]
    for line in current:
        offsets.append(offsets[-1] + len(line))
    comparison = SequenceMatcher(
        None,
        [line.rstrip("\r\n") for line in generated],
        [line.rstrip("\r\n") for line in current],
        autojunk=False,
    )
    return [
        (offsets[start], offsets[end])
        for kind, _, _, start, end in comparison.get_opcodes()
        if kind == "insert"
    ]


def manual_refresh_fragments(patch: PageUpdate, baseline: str) -> tuple[str, ...]:
    return tuple(
        text
        for start, end in manual_refresh_insertions(patch, baseline)
        if (text := patch.body[start:end].strip("\r\n")).strip()
    )


def editable_refresh_blocks(patch: PageUpdate, baseline: str) -> frozenset[str]:
    """Protect whole added blocks; mixed source paragraphs use literal preservation."""
    insertions = manual_refresh_insertions(patch, baseline)
    return frozenset(
        identity
        for identity, (start, end) in patch.blocks.items()
        if not any(left <= start and end <= right for left, right in insertions)
    )


def generated_refresh_baseline(kb_dir, view, page: str) -> str | None:
    """Locate the exact recorded generated bytes, through immutable revision history."""
    target = view.head.generated_baselines.get(page)
    if target is None or target == view.base_pages.get(page):
        return None
    identity, seen = view.head.knowledge_revision_id, set()
    while identity:
        if identity in seen:
            raise ValueError("Generated page baseline history contains a cycle")
        seen.add(identity)
        directory = kb_dir / ".ultrakb/knowledge" / view.scope.view_id / "revisions" / identity
        manifest = KnowledgeRevision.model_validate_json((directory / "manifest.json").read_text())
        if manifest.knowledge_revision_id != identity or manifest.view_id != view.scope.view_id:
            raise ValueError("Generated page baseline belongs to another revision")
        original = directory / "wiki" / page
        if (
            original.is_file()
            and not original.is_symlink()
            and HashRegistry.hash_file(original) == target
        ):
            return original.read_text("utf-8")
        identity = manifest.base_revision_id
    raise ValueError("The recorded generated page baseline is unavailable")
