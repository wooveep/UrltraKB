"""The captured third response remains replayable without any paid generation."""

import hashlib
import json
from pathlib import Path

from ultrakb.agent.retained_summary import reuse_saved_summary
from ultrakb.compile_checkpoints import CompileCheckpoints
from ultrakb.config import LlmCredentialBundle
from ultrakb.content_blocks import markdown_layout
from ultrakb.llm_execution import CompletionExecutor, ModelCallPolicy, RoleBindings
from ultrakb.locks import atomic_write_json
from ultrakb.model_task import TaskJournal, read_task, task_path

FIXTURE = Path(__file__).parent / "fixtures" / "summary-third-response.json"
RESPONSE_SHA256 = "49c3d3e62345a94c5c5127fc346b3109ba0a7f098e601744893b995506737e72"


def test_captured_third_summary_replays_without_changing_accepted_results_or_budget(kb_dir):
    case = json.loads(FIXTURE.read_text("utf-8"))
    raw = case["response"]
    assert hashlib.sha256(raw.encode()).hexdigest() == RESPONSE_SHA256
    executor = CompletionExecutor(
        RoleBindings("deepseek/deepseek-flash", LlmCredentialBundle(api_key="unused-offline")),
        ModelCallPolicy(max_calls=1000, retries=0),
    )
    executor.budget.restore(276, {"document_index": 270, "compile": 6})
    journal = TaskJournal(kb_dir, executor)
    checkpoint = CompileCheckpoints(kb_dir, journal.record, {"document": case["document"]}, {})
    for accepted in case["accepted_summaries"]:
        checkpoint.save(accepted["key"], accepted["request_digest"], accepted["result"])
    retained = {p: p.read_bytes() for p in checkpoint.directory.glob("payload-*.json")}
    checkpoint.claim_repair("summary:3", case["request_digest"])
    response_path = checkpoint.record_invalid_response(
        "summary:3",
        case["request_digest"],
        raw,
        stage="document-summary:3",
        response_protocol="summary-json",
        expected_sections=tuple(case["expected_sections"]),
        code="page_literal_conflict",
        detail="Captured whitespace and excerpt-boundary rejection",
        attempt=1,
    )
    # Restore the historical exhausted recovery state as input, without a send.
    manifest = json.loads(checkpoint.path.read_text())
    manifest["entries"]["summary:3"]["manual_retry_used"] = True
    atomic_write_json(checkpoint.path, manifest)
    budget = task_path(kb_dir, journal.record.task_id)
    before = budget.read_bytes()
    with executor.activate():
        result = reuse_saved_summary(
            checkpoint,
            "summary:3",
            case["request_digest"],
            case["batch"],
            protocol="summary-json",
            section_ranges=case["batch"]["output_sections"],
        )
    assert result is not None
    assert [section["id"] for section in result["sections"]] == case["expected_sections"]
    assert result["description"] == case["accepted_description"]
    actual = []
    for section in result["sections"]:
        tokens, _ = markdown_layout(section["content"])
        actual.extend(
            hashlib.sha256(token.content.rstrip("\n").encode()).hexdigest()
            for token in tokens
            if token.type == "fence"
        )
    assert len(actual) == 58
    # Ordinary fences retain generated bytes; explicit markers alone copy originals.
    manual = [
        token.content
        for section in json.loads(raw)["sections"]
        for token in markdown_layout(section["content"])[0]
        if token.type == "fence"
    ]
    delivered = [
        token.content
        for section in result["sections"]
        for token in markdown_layout(section["content"])[0]
        if token.type == "fence"
    ]
    assert len(manual) == 26
    assert all(body in delivered for body in manual)
    assert all(p.read_bytes() == value for p, value in retained.items())
    assert (kb_dir / response_path).read_bytes() == raw.encode()
    assert budget.read_bytes() == before
    assert read_task(kb_dir, journal.record.task_id).used == executor.calls == 276
    restored = CompileCheckpoints(kb_dir, journal.record, checkpoint.identity, {})
    assert restored.load("summary:3", case["request_digest"]) == result
    entry = json.loads(restored.path.read_text())["entries"]["summary:3"]
    assert entry["repair_used"] and entry["manual_retry_used"]
    assert entry["reused_response"]["response_sha256"] == RESPONSE_SHA256
